package com.aceteamup.entity;

import jakarta.persistence.*;
import lombok.*;
import org.hibernate.annotations.CreationTimestamp;

import java.math.BigDecimal;
import java.time.LocalDateTime;

/**
 * JPA Entity for the {@code match_recommendations} table.
 * Stores AI-generated compatibility scores between students for a given event.
 */
@Entity
@Table(
    name = "match_recommendations",
    uniqueConstraints = @UniqueConstraint(
        name = "uq_mr_student_recommended_event",
        columnNames = {"student_id", "recommended_student_id", "event_id"}
    )
)
@Data
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class MatchRecommendation {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "match_id", nullable = false, updatable = false)
    private Long matchId;

    /** The student who receives this recommendation. */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "student_id", nullable = false)
    private Student student;

    /** The student being recommended as a potential teammate. */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "recommended_student_id", nullable = false)
    private Student recommendedStudent;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "event_id", nullable = false)
    private Event event;

    /**
     * AI-computed compatibility score in [0.0000, 1.0000].
     * Higher is better.
     */
    @Column(name = "compatibility_score", nullable = false, precision = 5, scale = 4)
    @Builder.Default
    private BigDecimal compatibilityScore = BigDecimal.ZERO;

    /** Human-readable explanation generated by the AI model. */
    @Column(name = "explanation", columnDefinition = "TEXT")
    private String explanation;

    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;
}

